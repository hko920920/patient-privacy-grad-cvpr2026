#!/usr/bin/env python3
"""Build Audit V14 supplement tables from the verified V3.1 200-case run.

This generator reads only frozen machine-readable outputs.  It validates the
designed grid, paired mutation schedule, aggregate values, lineage equality,
artifact completeness, and independent-verifier result before writing LaTeX.
It does not execute the production validator or change any experiment result.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


METHOD_ORDER = (
    "B0_FIELD_PRESENCE",
    "B1_JSON_SCHEMA",
    "B2_MULTIPLICITY_ONLY",
    "B3_HASH_ONLY",
    "B4_ACCOUNTANT_ONLY",
    "A1_RUNTIME_ASSUMED_MATCHED",
    "A2_FULL_MINUS_VACUITY",
    "FULL",
)

METHOD_LABEL = {
    "B0_FIELD_PRESENCE": "B0 field presence",
    "B1_JSON_SCHEMA": "B1 JSON Schema",
    "B2_MULTIPLICITY_ONLY": "B2 multiplicity only",
    "B3_HASH_ONLY": "B3 hash only",
    "B4_ACCOUNTANT_ONLY": "B4 accountant only",
    "A1_RUNTIME_ASSUMED_MATCHED": "A1 runtime assumed matched",
    "A2_FULL_MINUS_VACUITY": "A2 full minus vacuity",
    "FULL": "FULL",
}

EXPECTED = {
    "B0_FIELD_PRESENCE": (100, 60, 0, 40),
    "B1_JSON_SCHEMA": (96, 60, 0, 40),
    "B2_MULTIPLICITY_ONLY": (100, 80, 0, 4),
    "B3_HASH_ONLY": (96, 60, 0, 40),
    "B4_ACCOUNTANT_ONLY": (88, 60, 0, 40),
    "A1_RUNTIME_ASSUMED_MATCHED": (12, 100, 188, 0),
    "A2_FULL_MINUS_VACUITY": (4, 100, 196, 0),
    "FULL": (0, 100, 200, 0),
}


def require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def load_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def latex(value: object) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in str(value))


def code(value: object) -> str:
    escaped = latex(value)
    escaped = escaped.replace(r"\_", r"\_\allowbreak ")
    escaped = escaped.replace("; ", r";\allowbreak ")
    return r"\texttt{" + escaped + "}"


def digest(value: object) -> str:
    return r"\seqsplit{\texttt{" + latex(value) + "}}"


def write_generated(path: Path, content: str) -> None:
    path.write_text(
        "% AUTO-GENERATED by "
        "scripts/build_validator_ablation_v3_1_supplement_tables.py.\n"
        "% Do not edit by hand; rebuild from the frozen V3.1 evidence.\n"
        + content.rstrip()
        + "\n",
        encoding="utf-8",
        newline="\n",
    )


def build_ablation(rows: list[dict[str, str]]) -> str:
    by_method = {row["method"]: row for row in rows}
    require(tuple(by_method) == METHOD_ORDER, "Unexpected aggregate method order")
    body: list[str] = []
    for method in METHOD_ORDER:
        row = by_method[method]
        observed = (
            int(row["unsafe_positives"]),
            int(row["valid_exact_decisions"]),
            int(row["exact_tuples"]),
            int(row["wrong_same_number"]),
        )
        require(
            observed == EXPECTED[method], f"Unexpected metrics for {method}: {observed}"
        )
        unsafe, valid, exact, same = observed
        label = METHOD_LABEL[method]
        if method == "FULL":
            label = r"\textbf{FULL}"
            unsafe_cell = r"\textbf{0/100 (0.00)}"
            valid_cell = r"\textbf{100/100 (1.00)}"
            exact_cell = r"\textbf{200/200 (1.00)}"
        else:
            unsafe_cell = f"{unsafe}/100 ({unsafe / 100:.2f})"
            valid_cell = f"{valid}/100 ({valid / 100:.2f})"
            exact_cell = f"{exact}/200 ({exact / 200:.2f})"
        body.append(
            " & ".join(
                [
                    label,
                    unsafe_cell,
                    valid_cell,
                    exact_cell,
                    str(same),
                    row["median_wall_ms"],
                    row["max_wall_ms"],
                ]
            )
            + r" \\"
        )
    return "\n".join(
        [
            r"\begingroup",
            r"\scriptsize",
            r"\setlength{\tabcolsep}{2.2pt}",
            r"\renewcommand{\arraystretch}{1.10}",
            r"\begin{longtable}{@{}p{.22\textwidth}p{.15\textwidth}p{.15\textwidth}p{.15\textwidth}p{.10\textwidth}p{.08\textwidth}p{.08\textwidth}@{}}",
            r"\caption{Controlled obligation projections and ablations on the designed 200-case suite. Raw fractions are deterministic case outcomes, not statistical estimates. Timing is descriptive wall-clock milliseconds.}\label{tab:supp-ablation-200}\\",
            r"\toprule",
            r"Probe / full contract & Unsafe positive & Valid exact & Exact tuple & Same-number & Median & Max \\",
            r"\midrule",
            r"\endfirsthead",
            r"\multicolumn{7}{l}{\itshape Table \thetable\ continued}\\",
            r"\toprule",
            r"Probe / full contract & Unsafe positive & Valid exact & Exact tuple & Same-number & Median & Max \\",
            r"\midrule",
            r"\endhead",
            r"\midrule \multicolumn{7}{r}{\itshape Continued on next page}\\",
            r"\endfoot",
            r"\bottomrule",
            r"\endlastfoot",
            *body,
            r"\end{longtable}",
            r"\endgroup",
        ]
    )


def build_allowed_grid(allowed: list[dict[str, Any]]) -> str:
    by_cell = {
        (case["stratum_id"], int(case["level"]), case["context_id"]): case
        for case in allowed
    }
    body: list[str] = []
    for stratum_index in range(1, 6):
        stratum = f"S{stratum_index}"
        for level in range(1, 6):
            cases = [
                by_cell[(stratum, level, f"C{context}")] for context in range(1, 5)
            ]
            first = cases[0]
            evidence = (
                f"n={first['selected_record_count']}; "
                f"kappa_e={first['observed_event_kappa']}; K={first['expected_k']}"
            )
            body.append(
                " & ".join(
                    [
                        code(f"{stratum} {first['stratum_name']}"),
                        f"L{level}; {latex(evidence)}",
                        *(code(case["case_id"]) for case in cases),
                    ]
                )
                + r" \\"
            )
    return "\n".join(
        [
            r"\begingroup",
            r"\fontsize{6.4}{7.3}\selectfont",
            r"\setlength{\tabcolsep}{1.6pt}",
            r"\renewcommand{\arraystretch}{1.08}",
            r"\begin{longtable}{@{}p{.18\textwidth}p{.14\textwidth}p{.16\textwidth}p{.16\textwidth}p{.16\textwidth}p{.16\textwidth}@{}}",
            r"\caption{Complete $5\times5\times4$ allowed-case coverage matrix. C1 is canonical, C2 has irregular half-open supports, C3 adds non-selected decoy rows, and C4 permutes file order while preserving selected semantics.}\label{tab:supp-allowed-grid-200}\\",
            r"\toprule",
            r"Stratum / route & Level evidence & C1 & C2 & C3 & C4 \\",
            r"\midrule",
            r"\endfirsthead",
            r"\multicolumn{6}{l}{\itshape Table \thetable\ continued}\\",
            r"\toprule",
            r"Stratum / route & Level evidence & C1 & C2 & C3 & C4 \\",
            r"\midrule",
            r"\endhead",
            r"\midrule \multicolumn{6}{r}{\itshape Continued on next page}\\",
            r"\endfoot",
            r"\bottomrule",
            r"\endlastfoot",
            *body,
            r"\end{longtable}",
            r"\endgroup",
        ]
    )


def build_operator_matrix(non_allow: list[dict[str, Any]]) -> str:
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for case in non_allow:
        grouped[case["operator_id"]].append(case)
    body: list[str] = []
    for index in range(1, 26):
        operator = f"O{index:02d}"
        cases = sorted(grouped[operator], key=lambda case: case["case_id"])
        require(len(cases) == 4, f"{operator} does not have four cases")
        mutation = cases[0]["description"].split(": ", 1)[-1].rstrip(".")
        outcome = f"{cases[0]['expected_release_status']}; {cases[0]['expected_issue_code'] or 'path-only'}"
        parents = "; ".join(case["parent_case_id"] for case in cases)
        body.append(
            " & ".join([code(operator), latex(mutation), code(outcome), code(parents)])
            + r" \\"
        )
    return "\n".join(
        [
            r"\begingroup",
            r"\fontsize{6.2}{7.1}\selectfont",
            r"\setlength{\tabcolsep}{2pt}",
            r"\renewcommand{\arraystretch}{1.08}",
            r"\begin{longtable}{@{}p{.06\textwidth}p{.28\textwidth}p{.28\textwidth}p{.34\textwidth}@{}}",
            r"\caption{Complete $25\times4$ paired non-allow operator--parent matrix. Each allowed parent appears exactly once. The diagnostic shown is the predeclared primary result; documented cascades may accompany it.}\label{tab:supp-operator-grid-200}\\",
            r"\toprule",
            r"ID & Direct semantic mutation & Expected status; primary diagnostic & Four distinct allowed parents \\",
            r"\midrule",
            r"\endfirsthead",
            r"\multicolumn{4}{l}{\itshape Table \thetable\ continued}\\",
            r"\toprule",
            r"ID & Direct semantic mutation & Expected status; primary diagnostic & Four distinct allowed parents \\",
            r"\midrule",
            r"\endhead",
            r"\midrule \multicolumn{4}{r}{\itshape Continued on next page}\\",
            r"\endfoot",
            r"\bottomrule",
            r"\endlastfoot",
            *body,
            r"\end{longtable}",
            r"\endgroup",
        ]
    )


