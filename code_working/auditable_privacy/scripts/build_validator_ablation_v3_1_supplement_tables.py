def build_artifact_inputs(paths: dict[str, Path], repo_root: Path) -> str:
    body = []
    for name, path in sorted(paths.items()):
        relative = path.relative_to(repo_root).as_posix()
        body.append(
            f"{latex(name)}: \\path{{{relative}}} & {digest(sha256_file(path))} \\\\"
        )
    return "\n".join(
        [
            r"\begingroup",
            r"\fontsize{6.3}{7.2}\selectfont",
            r"\setlength{\tabcolsep}{2pt}",
            r"\begin{longtable}{@{}p{.55\textwidth}p{.41\textwidth}@{}}",
            r"\caption{Claim-bearing inputs for the designed 200-case table. The verification index separately binds the artifact index, verifier source, and verification result.}\label{tab:supp-ablation-inputs-200}\\",
            r"\toprule",
            r"Repository-relative input & SHA-256 \\",
            r"\midrule",
            r"\endfirsthead",
            r"\multicolumn{2}{l}{\itshape Table \thetable\ continued}\\",
            r"\toprule Repository-relative input & SHA-256 \\",
            r"\midrule",
            r"\endhead",
            r"\bottomrule",
            r"\endfoot",
            *body,
            r"\end{longtable}",
            r"\endgroup",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-root", type=Path, default=Path(__file__).resolve().parents[1]
    )
    parser.add_argument("--paper-root", type=Path, default=None)
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    paper_root = (
        args.paper_root.resolve()
        if args.paper_root
        else (
            repo_root.parent / "AAAI27_7p_compressed" / "01_audit_reporting_paper"
        ).resolve()
    )
    report_root = repo_root / "reports/validator_ablation_v3_1_200_001"
    output_root = paper_root / "supplement_v14_generated"
    output_root.mkdir(parents=True, exist_ok=True)

    paths = {
        "frozen protocol": repo_root
        / "paper_notes/AAAI27_AUDIT_V19_CONFORMANCE_200_PROTOCOL_V1_2026-07-28.md",
        "runner": repo_root / "scripts/run_validator_ablation_v3_1.py",
        "verifier": repo_root / "scripts/verify_validator_ablation_v3_2.py",
        "cases": report_root / "cases.json",
        "aggregate metrics": report_root / "aggregate_metrics.csv",
        "input lineage": report_root / "v3_input_lineage_equivalence.json",
        "execution status": report_root / "execution_status.json",
        "artifact index": report_root / "artifact_index.json",
        "independent verification": report_root / "independent_verification.json",
        "verification index": report_root / "verification_index.json",
    }
    for name, path in paths.items():
        require(path.is_file(), f"Missing {name}: {path}")

    cases_payload = load_json(paths["cases"])
    cases = cases_payload["cases"]
    allowed = [case for case in cases if case["case_kind"] == "allowed"]
    non_allow = [case for case in cases if case["case_kind"] == "non_allow"]
    require(
        len(cases) == 200 and len(allowed) == 100 and len(non_allow) == 100,
        "Case counts changed",
    )
    require(
        Counter(case["stratum_id"] for case in allowed)
        == {f"S{i}": 20 for i in range(1, 6)},
        "Allowed stratum coverage changed",
    )
    require(
        Counter(case["context_id"] for case in allowed)
        == {f"C{i}": 25 for i in range(1, 5)},
        "Allowed context coverage changed",
    )
    require(
        len({case["case_id"] for case in cases}) == 200,
        "Case identifiers are not unique",
    )
    require(
        len({case["input_triple_sha256"] for case in cases}) == 200,
        "Input triples are not unique",
    )
    require(
        len({case["parent_case_id"] for case in non_allow}) == 100,
        "Parent schedule is not one-to-one",
    )
    require(
        Counter(case["operator_id"] for case in non_allow)
        == {f"O{i:02d}": 4 for i in range(1, 26)},
        "Operator schedule changed",
    )

    full_mapping_hashes: set[str] = set()
    selected_mapping_hashes: set[str] = set()
    for case in allowed:
        report = load_json(repo_root / case["report_path"])
        full_mapping_hashes.add(report["pipeline"]["mapping_file_sha256"])
        selected_mapping_hashes.add(report["pipeline"]["selected_mapping_sha256"])
    require(
        len(full_mapping_hashes) == 100, "Expected 100 distinct full mapping hashes"
    )
    require(
        len(selected_mapping_hashes) == 50,
        "Expected 50 selected-semantic mapping hashes",
    )

    execution = load_json(paths["execution status"])
    require(
        execution["gates_passed"] is True
        and execution["v3_input_content_equal"] is True,
        "Runner gates failed",
    )
    lineage = load_json(paths["input lineage"])
    require(lineage["all_200_input_content_equal"] is True, "V3 input lineage mismatch")
    require(
        lineage["all_200_oracle_metadata_equal"] is True, "V3 oracle lineage mismatch"
    )
    require(len(lineage["cases"]) == 200, "Lineage case count changed")

    verification = load_json(paths["independent verification"])
    require(verification["passed"] is True, "Independent verification failed")
    require(
        verification["check_count"] == 20909 and verification["failure_count"] == 0,
        "Verification counts changed",
    )
    require(
        verification["standard_library_only"] is True,
        "Verifier import boundary changed",
    )
    require(
        verification["independent_grid_operator_oracle"] is True,
        "Independent oracle missing",
    )
    require(
        verification["internal_registry_hash_closure"] is True,
        "Registry hash closure missing",
    )

    artifact_index = load_json(paths["artifact index"])
    require(len(artifact_index["files"]) == 627, "Artifact-index count changed")
    require(
        sum("/case_inputs/" in item["path"] for item in artifact_index["files"]) == 600,
        "Raw case-input count changed",
    )

    aggregate = load_csv(paths["aggregate metrics"])
    outputs = {
        "ablation_metrics.tex": build_ablation(aggregate),
        "allowed_grid.tex": build_allowed_grid(allowed),
        "operator_matrix.tex": build_operator_matrix(non_allow),
        "verification_surface_summary.tex": build_verification_summary(),
        "verification_surface_detailed.tex": build_verification_detailed(),
        "artifact_inputs.tex": build_artifact_inputs(paths, repo_root),
    }
    for filename, content in outputs.items():
        write_generated(output_root / filename, content)

    generator_path = Path(__file__).resolve()
    manifest = {
        "schema_version": "audit_validator_ablation_v3_1_supplement_tables_v1.0",
        "generator": {
            "path": generator_path.relative_to(repo_root).as_posix(),
            "sha256": sha256_file(generator_path),
        },
        "counts": {
            "allowed_cases": 100,
            "non_allow_cases": 100,
            "operators": 25,
            "full_mapping_hashes": len(full_mapping_hashes),
            "selected_semantic_mapping_hashes": len(selected_mapping_hashes),
            "artifact_index_files": len(artifact_index["files"]),
            "raw_case_input_files": 600,
            "independent_checks": verification["check_count"],
        },
        "inputs": {
            name: {
                "path": path.relative_to(repo_root).as_posix(),
                "bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
            for name, path in sorted(paths.items())
        },
        "outputs": {
            filename: {
                "path": (output_root / filename).relative_to(paper_root).as_posix(),
                "bytes": (output_root / filename).stat().st_size,
                "sha256": sha256_file(output_root / filename),
            }
            for filename in sorted(outputs)
        },
    }
    provenance_path = output_root / "provenance.json"
    provenance_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    print(
        json.dumps(
            {
                "status": "PASS",
                "output_root": str(output_root),
                "outputs": len(outputs),
                "allowed": len(allowed),
                "non_allow": len(non_allow),
                "independent_checks": verification["check_count"],
                "provenance_sha256": sha256_file(provenance_path),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
